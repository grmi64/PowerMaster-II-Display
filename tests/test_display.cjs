const assert=require('assert/strict');
const {DisplayModel}=require('../Sources/display.js');
const model=new DisplayModel();
const reading=(f,frame,age=.1)=>({status:'Live',age,frames:frame,values:[f,.5,f?1.2:0]});
assert.equal(model.sample(reading(100,1),0,2).peak,100);
assert.equal(model.sample(reading(40,2),1000,2).peak,100);
assert.equal(model.sample(reading(30,3),2100,2).peak,30);
model.reset();assert.equal(model.sample(reading(200,4),2200,-1).peak,200);
assert.equal(model.sample(reading(10,5),90000,-1).peak,200);
model.reset();assert.equal(model.sample(reading(10,5),90001,-1).peak,10);
assert.equal(model.sample(reading(100,6),90002,0).peak,null);
assert.equal(model.sample(reading(0,7),90003,2).swr,null);
const stale=model.sample(reading(900,8,2.1),90004,2);assert.equal(stale.live,false);assert.equal(stale.peak,null);assert.equal(stale.forward,0);
assert.equal(model.scale('forward',52.91,'auto',0),100);
assert.equal(model.scale('forward',900,'auto',1),1500);
assert.equal(model.scale('forward',50,'auto',2000),1500);
assert.equal(model.scale('forward',50,'auto',6001),100);
assert.equal(model.scale('forward',900,'250',6002),250,'Fixed scale does not change with power');
assert.equal(model.scale('reflected',1,'auto',0),5);
const fs=require('fs'),html=fs.readFileSync('Sources/powermaster_ui.html','utf8'),native=fs.readFileSync('Sources/App.swift','utf8');
for(const id of ['profile','hold','reset','scale','refScale','compact','stayTop'])assert(html.includes('id="'+id+'"'));
assert(native.includes('window.level = onTop ? .floating : .normal'));
assert(native.includes('small != compact'));
